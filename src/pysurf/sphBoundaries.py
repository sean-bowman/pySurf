
# -- pySurf: SPH Boundaries -- #

'''

Solid walls for SPH: layers of fixed boundary particles, and a guard that keeps fluid on the
right side of them.

Boundary particles follow the dynamic boundary condition of Crespo et al. (2007): they take part
in the density sum and carry a pressure from the equation of state, but they do not move. Fluid
approaching a wall compresses the boundary particles' kernel neighborhoods, their pressure rises,
and the pressure term pushes the fluid back. Several layers keep a fluid particle's kernel support
full at the wall.

    ContainerBoundary   an axis-aligned box with an open top: a sloshing tank
    BedBoundary         a bed of any profile from `pysurf.bathymetry`, with optional vertical walls
                        at either end: a beach, or a channel; the offshore wall can be driven as a
                        piston; in 3D extruded across a channel, walled or periodic
    ShearedBedBoundary  a 3D bed whose depth contours run obliquely across the channel, each row of
                        particles with an offshore wall driven as a piston of its own
    HeightFieldBoundary a 3D bed of any shape (`pysurf.bathymetry.HeightField`) in a rectangular
                        tank with vertical walls on all four sides

Each produces its particle positions and an `enforce` step the solver calls after every
integration. Enforcement is the fallback, not the boundary condition: it catches the rare particle
that a strong impact drives through the particle layers, such as a plunging jet landing on the
beach, by moving it back into the water and removing its velocity into the wall.

References:
-----------
Crespo, A.J.C., Gomez-Gesteira, M. & Dalrymple, R.A. (2007) -- Boundary conditions generated by
    dynamic particles in SPH methods, CMC: Computers, Materials & Continua 5(3), 173-184.
Monaghan & Kos (1999) -- Solitary waves on a Cretan beach, J. Waterway, Port, Coastal, Ocean
    Eng. 125(3), 145-154.

----------------------------------------------------------------------
                            Validation status
----------------------------------------------------------------------

Geometry and bookkeeping only; the physics of the wall is the solver's. tests/testSphBoundaries.py
checks that boundary layers sit at the intended offsets from the wall, keep the lattice spacing
along it, and that enforcement returns a penetrating particle to the water with no velocity into
the wall; for the height-field bed, that each layer lies its offset below the bed along the
normal and that the walls close the tank's corners. The wall's effect on a flow is validated through the sloshing tank in
tests/testValidationSloshing.py.

Sean Bowman [10/11/2026]

'''

# Standard library imports
from __future__ import annotations

# Third-party imports
import numpy as np

# Local imports
from pysurf.bathymetry import Bathymetry, HeightField
from pysurf.sphParticles import ParticleSystem

class ContainerBoundary:

    '''

    An axis-aligned container: floor and side walls, open at the top unless asked otherwise.

    Parameters:
    -----------
    containerMin : np.ndarray
        Lower corner of the container interior [m]
    containerMax : np.ndarray
        Upper corner of the container interior [m]
    spacing : float
        Lattice spacing, matching the fluid's [m]
    nLayers : int
        Boundary particle layers behind each face
    openTop : bool
        No boundary particles on the top face

    '''

    def __init__(self, containerMin: np.ndarray, containerMax: np.ndarray, spacing: float,
                 nLayers: int = 3, openTop: bool = True) -> None:

        self.containerMin = np.asarray(containerMin, dtype = float).copy()
        self.containerMax = np.asarray(containerMax, dtype = float).copy()
        self.spacing = spacing      # [m]
        self.nLayers = nLayers
        self.openTop = openTop

    @property
    def dimensions(self) -> int:
        '''Number of spatial dimensions.'''
        return len(self.containerMin)

    def positions(self) -> np.ndarray:

        '''

        Boundary particle positions: the shell nLayers deep around the container interior, less
        the top face when open. Each face's layers are anchored to that face, half a spacing
        apart, so the gap to the fluid is one spacing on every face whatever the container size.

        '''

        s, layers = self.spacing, self.nLayers
        offsets = (np.arange(layers) + 0.5) * s

        axes = []
        for axis, (low, high) in enumerate(zip(self.containerMin, self.containerMax)):
            pieces = [low - offsets[::-1], np.arange(low + s / 2.0, high, s)]
            if not (self.openTop and axis == self.dimensions - 1):
                pieces.append(high + offsets)
            axes.append(np.concatenate(pieces))
        grids = np.meshgrid(*axes, indexing = 'xy')
        points = np.column_stack([grid.ravel() for grid in grids])

        interior = np.all((points > self.containerMin) & (points < self.containerMax), axis = 1)
        if self.openTop:
            # Above the floor and between the side walls is interior all the way up
            between = np.all((points[:, :-1] > self.containerMin[:-1]) & (points[:, :-1] < self.containerMax[:-1]), axis = 1)
            interior = between & (points[:, -1] > self.containerMin[-1])

        return points[~interior]

    def enforce(self, particles: ParticleSystem) -> None:

        '''

        Return any fluid particle outside the container to its face and remove its velocity
        through that face.

        '''

        fluid = particles.isFluid
        positions, velocities = particles.positions, particles.velocities

        for axis in range(self.dimensions):
            below = fluid & (positions[:, axis] < self.containerMin[axis])
            positions[below, axis] = self.containerMin[axis]
            velocities[below, axis] = np.maximum(velocities[below, axis], 0.0)

            if axis == self.dimensions - 1 and self.openTop:
                continue
            above = fluid & (positions[:, axis] > self.containerMax[axis])
            positions[above, axis] = self.containerMax[axis]
            velocities[above, axis] = np.minimum(velocities[above, axis], 0.0)

class BedBoundary:

    '''

    A bed of any profile, with optional vertical walls at its offshore and shoreward ends; 2D, or
    extruded across a channel of the given width in 3D.

    Bed particles sit in layers below the bed, offset along its normal by (layer + 1/2) spacing,
    and spaced one lattice spacing apart along it. The offshore wall's layers sit behind x = startX
    and run from below the bed to `wallTop`; the shoreward wall's sit beyond x = endX up to
    `endWallTop`. In 3D the bed and offshore wall are repeated across the channel, and front and
    back walls close its sides. The vertical axis is the last coordinate.

    The offshore wall can be driven as a piston: `attachPiston` takes its particles, and
    `movePiston` moves them and gives them the piston's velocity. Over a flat or rising bed the
    wall's columns, which reach below the bed, keep the corner closed as it advances.

    Parameters:
    -----------
    bathymetry : Bathymetry
        The bed profile
    spacing : float
        Lattice spacing, matching the fluid's [m]
    nLayers : int
        Boundary particle layers
    wallTop : float | None
        Top of the offshore wall, and of the side walls in 3D [m]; None for no offshore wall
    width : float | None
        Channel width for a 3D boundary [m]; None for 2D
    endWallTop : float | None
        Top of the shoreward wall [m], 2D only; None for no shoreward wall
    periodic : bool
        In 3D, the channel is periodic across its width instead of walled: the bed and end walls
        span y in [0, width) at the lattice spacing, which must divide the width, and there are no
        side walls. The solver's `periodicWidth` must be the same width.

    '''

    def __init__(self, bathymetry: Bathymetry, spacing: float, nLayers: int = 3,
                 wallTop: float | None = None, width: float | None = None, endWallTop: float | None = None,
                 periodic: bool = False) -> None:

        self.bathymetry = bathymetry
        self.spacing = spacing      # [m]
        self.nLayers = nLayers
        self.wallTop = wallTop      # [m]
        self.width = width          # [m]
        self.endWallTop = endWallTop                # [m]
        self.periodic = periodic and width is not None
        self.wallX = bathymetry.startX              # [m], the offshore wall, which a piston moves
        self._pistonMask: np.ndarray | None = None

    def _profilePositions(self) -> np.ndarray:

        '''The 2D bed and offshore wall layers, in (x, z).'''

        s = self.spacing
        bedX, bedZ = self.bathymetry.sample(s)
        bedNormal = self.bathymetry.normal(bedX)

        layers = []
        for layer in range(self.nLayers):
            offset = (layer + 0.5) * s
            layers.append(np.column_stack([bedX, bedZ]) - offset * bedNormal)

        # The wall columns reach down past the deepest bed layer, so the corners are closed
        for wallX, top, side in ((self.bathymetry.startX, self.wallTop, -1.0),
                                 (self.bathymetry.endX, self.endWallTop, 1.0)):
            if top is None:
                continue
            bottom = float(self.bathymetry.elevation(wallX)) - self.nLayers * s
            heights = np.arange(bottom + s / 2.0, top, s)
            for layer in range(self.nLayers):
                layers.append(np.column_stack([np.full_like(heights, wallX + side * (layer + 0.5) * s), heights]))

        return np.vstack(layers)

    def positions(self) -> np.ndarray:

        '''Boundary particle positions, shape (N, 2), or (N, 3) with a channel width.'''

        profile = self._profilePositions()
        if self.width is None:
            return profile

        s, layers = self.spacing, self.nLayers
        offsets = (np.arange(layers) + 0.5) * s

        if self.periodic:
            # One lattice row per particle column across the period, no side walls
            across = np.arange(s / 2.0, self.width, s)
            return np.column_stack([np.repeat(profile[:, 0], across.size), np.tile(across, len(profile)),
                                    np.repeat(profile[:, 1], across.size)])

        # Bed and offshore wall repeated across the channel and under the side walls
        across = np.concatenate([-offsets[::-1], np.arange(s / 2.0, self.width, s), self.width + offsets])
        extruded = np.column_stack([np.repeat(profile[:, 0], across.size), np.tile(across, len(profile)),
                                    np.repeat(profile[:, 1], across.size)])

        # Side walls: every lattice height from below the bed to the wall top, at each bed station
        top = self.wallTop if self.wallTop is not None else float(np.max(self.bathymetry.z)) + layers * s
        bedX, _ = self.bathymetry.sample(s)
        heights = np.arange(float(np.min(self.bathymetry.z)) - layers * s + s / 2.0, top, s)
        xGrid, zGrid = np.meshgrid(bedX, heights, indexing = 'xy')
        keep = zGrid > self.bathymetry.elevation(xGrid) - layers * s
        xWall, zWall = xGrid[keep], zGrid[keep]
        sides = [np.column_stack([xWall, np.full_like(xWall, y), zWall])
                 for y in np.concatenate([-offsets, self.width + offsets])]

        return np.vstack([extruded] + sides)

    def attachPiston(self, particles: ParticleSystem) -> None:

        '''

        Take the offshore wall's particles, the boundary particles behind x = startX, as a piston.

        Raises:
        -------
        ValueError : If the boundary has no offshore wall.

        '''

        if self.wallTop is None:
            raise ValueError('A piston needs the offshore wall; give the boundary a wallTop.')
        self._pistonMask = (~particles.isFluid) & (particles.positions[:, 0] < self.bathymetry.startX - 0.25 * self.spacing)

    def movePiston(self, particles: ParticleSystem, x: float, velocity: float) -> None:

        '''

        Move the offshore wall to x [m], moving along the channel at `velocity` [m/s].

        Raises:
        -------
        RuntimeError : If `attachPiston` was not called first.

        '''

        if self._pistonMask is None:
            raise RuntimeError('No piston attached. Call attachPiston first.')
        particles.positions[self._pistonMask, 0] += x - self.wallX
        particles.velocities[self._pistonMask] = 0.0
        particles.velocities[self._pistonMask, 0] = velocity
        self.wallX = x

    def enforce(self, particles: ParticleSystem) -> None:

        '''

        Return fluid that has crossed the bed or a wall to the water side, a quarter spacing
        clear of the surface, and remove its velocity into the solid; past a piston, the velocity
        relative to it.

        '''

        fluid = np.nonzero(particles.isFluid)[0]
        positions, velocities = particles.positions, particles.velocities
        clearance = 0.25 * self.spacing

        # Bed: compare each particle with the bed elevation beneath it, in the (x, vertical) plane
        bedZ = self.bathymetry.elevation(positions[fluid, 0])
        under = fluid[positions[fluid, -1] < bedZ + clearance]
        if under.size:
            positions[under, -1] = self.bathymetry.elevation(positions[under, 0]) + clearance
            normal = self.bathymetry.normal(positions[under, 0])
            planeVelocity = velocities[under][:, [0, -1]]
            inward = np.sum(planeVelocity * normal, axis = 1)
            into = inward < 0.0
            correction = inward[into, None] * normal[into]
            velocities[under[into], 0] -= correction[:, 0]
            velocities[under[into], -1] -= correction[:, 1]

        # Side walls of a 3D channel
        if self.width is not None and not self.periodic:
            for bound, side in ((clearance, 'low'), (self.width - clearance, 'high')):
                if side == 'low':
                    outside = fluid[positions[fluid, 1] < bound]
                    velocities[outside, 1] = np.maximum(velocities[outside, 1], 0.0)
                else:
                    outside = fluid[positions[fluid, 1] > bound]
                    velocities[outside, 1] = np.minimum(velocities[outside, 1], 0.0)
                positions[outside, 1] = bound

        # Offshore wall, which may be a moving piston, and the shoreward end of the profile
        endX = self.bathymetry.endX
        if self.wallTop is not None:
            pistonSpeed = float(particles.velocities[self._pistonMask, 0][0]) if (
                self._pistonMask is not None and self._pistonMask.any()) else 0.0
            behind = fluid[positions[fluid, 0] < self.wallX + clearance]
            positions[behind, 0] = self.wallX + clearance
            velocities[behind, 0] = np.maximum(velocities[behind, 0], pistonSpeed)
        limit = endX - clearance if self.endWallTop is not None else endX
        beyond = fluid[positions[fluid, 0] > limit]
        positions[beyond, 0] = limit
        velocities[beyond, 0] = np.minimum(velocities[beyond, 0], 0.0)

class ShearedBedBoundary:

    '''

    A bed whose depth contours run obliquely across a 3D channel: the elevation at (x, y) is the
    profile's at x - shear y, a 2D bed sheared across the channel's width.

    Particle rows sit at the lattice spacing across the channel, y = (r + 1/2) s for r = 0 to
    rows - 1. Each row carries the 2D bed's layers and its offshore and shoreward walls
    (`BedBoundary` in 2D), moved along x by shear y. Side walls close the channel at y = 0 and
    y = width, every lattice height from below the bed to the wall top.

    Each row's offshore wall is a piston of its own (`movePiston`), so rows whose water is at
    different stages of the same flow can each have their wall follow it.

    Parameters:
    -----------
    bathymetry : Bathymetry
        The bed profile along x at y = 0
    spacing : float
        Lattice spacing [m]; it must divide the width
    width : float
        Channel width [m]
    shear : float
        dx/dy of the depth contours, tan of their angle to the y axis [-]
    nLayers : int
        Boundary particle layers
    wallTop : float
        Top of the offshore and side walls [m]
    endWallTop : float | None
        Top of the shoreward wall [m]; None for none

    '''

    def __init__(self, bathymetry: Bathymetry, spacing: float, width: float, shear: float, nLayers: int = 3,
                 wallTop: float = 1.0, endWallTop: float | None = None) -> None:

        self.bathymetry = bathymetry
        self.spacing = spacing                  # [m]
        self.width = width                      # [m]
        self.shear = shear                      # [-]
        self.nLayers = nLayers
        self.wallTop = wallTop                  # [m]
        self.endWallTop = endWallTop            # [m]
        self.rows = int(round(width / spacing))
        self.wallX = bathymetry.startX + shear * self.rowY                 # [m], each row's offshore wall
        self.pistonSpeed = np.zeros(self.rows)                             # [m/s]
        self._localPiston = np.array([], dtype = np.intp)
        self._localRow = np.array([], dtype = np.intp)
        self._start: int | None = None

    @property
    def rowY(self) -> np.ndarray:
        '''Spanwise position of each particle row [m].'''
        return (np.arange(self.rows) + 0.5) * self.spacing

    def rowOf(self, y: np.ndarray) -> np.ndarray:
        '''The row a spanwise position lies in.'''
        return np.clip(np.floor(np.asarray(y) / self.spacing).astype(np.intp), 0, self.rows - 1)

    def positions(self) -> np.ndarray:

        '''Boundary particle positions, shape (N, 3): the rows first, then the side walls.'''

        s, layers, bed = self.spacing, self.nLayers, self.bathymetry
        profile = BedBoundary(bed, s, nLayers = layers, wallTop = self.wallTop,
                              endWallTop = self.endWallTop)._profilePositions()
        offshore = profile[:, 0] < bed.startX - 0.25 * s
        blocks = [np.column_stack([profile[:, 0] + self.shear * y, np.full(len(profile), y), profile[:, 1]])
                  for y in self.rowY]
        self._localPiston = np.concatenate([np.flatnonzero(offshore) + r * len(profile) for r in range(self.rows)])
        self._localRow = np.repeat(np.arange(self.rows), np.count_nonzero(offshore))

        # Side walls: every lattice height from below the bed to the wall top along the profile
        bedX, _ = bed.sample(s)
        bedX = np.concatenate([np.arange(bed.startX - layers * s + s / 2.0, bed.startX, s), bedX])
        heights = np.arange(float(np.min(bed.z)) - layers * s + s / 2.0, self.wallTop, s)
        xGrid, zGrid = np.meshgrid(bedX, heights, indexing = 'xy')
        keep = zGrid > bed.elevation(np.clip(xGrid, bed.startX, bed.endX)) - layers * s
        offsets = (np.arange(layers) + 0.5) * s
        for y in np.concatenate([-offsets, self.width + offsets]):
            blocks.append(np.column_stack([xGrid[keep] + self.shear * y, np.full(int(keep.sum()), y), zGrid[keep]]))

        return np.vstack(blocks)

    def attach(self, firstIndex: int) -> None:

        '''Record where this boundary's particles start in the particle system, as `positions` laid them out.'''

        self._start = firstIndex

    def movePiston(self, particles: ParticleSystem, row: int, x: float, velocity: float) -> None:

        '''Move one row's offshore wall to x [m], moving along the channel at `velocity` [m/s].'''

        if self._start is None:
            raise RuntimeError('The boundary is not attached to a particle system. Call attach first.')
        members = self._start + self._localPiston[self._localRow == row]
        particles.positions[members, 0] += x - self.wallX[row]
        particles.velocities[members] = 0.0
        particles.velocities[members, 0] = velocity
        self.wallX[row] = x
        self.pistonSpeed[row] = velocity

    def enforce(self, particles: ParticleSystem) -> None:

        '''

        Return fluid that has crossed the bed or a wall to the water side, a quarter spacing
        clear of it, and remove its velocity into the solid; past a piston, the velocity relative
        to it.

        '''

        fluid = np.nonzero(particles.isFluid)[0]
        positions, velocities = particles.positions, particles.velocities
        clearance = 0.25 * self.spacing
        bed, shear = self.bathymetry, self.shear

        # Bed, with its normal in 3D: (-f', shear f', 1) for z = f(x - shear y)
        along = positions[fluid, 0] - shear * positions[fluid, 1]
        under = fluid[positions[fluid, 2] < bed.elevation(along) + clearance]
        if under.size:
            along = positions[under, 0] - shear * positions[under, 1]
            positions[under, 2] = bed.elevation(along) + clearance
            slope = bed.slope(along)
            normal = np.column_stack([-slope, shear * slope, np.ones_like(slope)])
            normal /= np.linalg.norm(normal, axis = 1)[:, None]
            inward = np.sum(velocities[under] * normal, axis = 1)
            into = inward < 0.0
            velocities[under[into]] -= inward[into, None] * normal[into]

        # Side walls
        low = fluid[positions[fluid, 1] < clearance]
        positions[low, 1] = clearance
        velocities[low, 1] = np.maximum(velocities[low, 1], 0.0)
        high = fluid[positions[fluid, 1] > self.width - clearance]
        positions[high, 1] = self.width - clearance
        velocities[high, 1] = np.minimum(velocities[high, 1], 0.0)

        # Each row's offshore wall, and the shoreward end
        rows = self.rowOf(positions[fluid, 1])
        behind = positions[fluid, 0] < self.wallX[rows] + clearance
        members = fluid[behind]
        positions[members, 0] = self.wallX[rows[behind]] + clearance
        velocities[members, 0] = np.maximum(velocities[members, 0], self.pistonSpeed[rows[behind]])
        limit = bed.endX + shear * positions[fluid, 1] - (clearance if self.endWallTop is not None else 0.0)
        beyond = positions[fluid, 0] > limit
        members = fluid[beyond]
        positions[members, 0] = limit[beyond]
        velocities[members, 0] = np.minimum(velocities[members, 0], 0.0)

class HeightFieldBoundary:

    '''

    A bed given as a height field, in a rectangular tank whose vertical walls stand on the field's
    bounds: an offshore wall at x = startX, a shoreward wall at x = endX, and side walls at
    y = startY and y = endY.

    Bed particles sit on the lattice's columns, x = startX + (i + 1/2) s and y = startY + (j + 1/2) s,
    in layers below the bed along its local normal at (layer + 1/2) s, as `BedBoundary` lays them
    in 2D. Each wall's layers stand behind its plane at (layer + 1/2) s, on the fluid lattice's
    heights (`latticeFloor` + (k + 1/2) s) from below the bed's deepest layer up to `wallTop`. The
    side walls run past the end walls by their own thickness, so the corners are closed. With no
    viscosity between fluid and boundary particles (the solver's default) every wall is free-slip,
    so the wall at y = startY can stand for a plane of symmetry.

    The columns are spaced s in x and y, so on a slope the layers' particles lie s / cos(slope)
    apart along the bed: 0.2 percent on a 1:15 slope.

    Parameters:
    -----------
    field : HeightField
        The bed, with its still water level; its bounds are the tank's walls
    spacing : float
        Lattice spacing, matching the fluid's [m]
    nLayers : int
        Boundary particle layers
    wallTop : float
        Top of the walls [m]
    offshoreWall : bool
        A wall at x = startX
    endWall : bool
        A wall at x = endX; without it, fluid past endX returns to it

    '''

    def __init__(self, field: HeightField, spacing: float, nLayers: int = 3, wallTop: float = 1.0,
                 offshoreWall: bool = True, endWall: bool = True) -> None:

        self.field = field
        self.spacing = spacing                  # [m]
        self.nLayers = nLayers
        self.wallTop = wallTop                  # [m]
        self.offshoreWall = offshoreWall
        self.endWall = endWall

    @property
    def latticeFloor(self) -> float:
        '''The level the fluid lattice's heights are counted from: the bed's lowest point [m].'''
        return self.field.lowestElevation()

    def columns(self) -> tuple[np.ndarray, np.ndarray]:

        '''The lattice's column positions along x and along y inside the walls [m].'''

        s = self.spacing
        startX, endX, startY, endY = self.field.bounds

        return np.arange(startX + 0.5 * s, endX, s), np.arange(startY + 0.5 * s, endY, s)

    def positions(self) -> np.ndarray:

        '''Boundary particle positions, shape (N, 3): the bed's layers, then the walls.'''

        s, layers, field = self.spacing, self.nLayers, self.field
        startX, endX, startY, endY = field.bounds
        xs, ys = self.columns()

        # The bed's layers, each offset along the local normal
        gridX, gridY = np.meshgrid(xs, ys, indexing = 'xy')
        gridX, gridY = gridX.ravel(), gridY.ravel()
        surface = np.column_stack([gridX, gridY, field.elevation(gridX, gridY)])
        normal = field.normal(gridX, gridY)
        blocks = [surface - (layer + 0.5) * s * normal for layer in range(layers)]

        # A wall's columns run on the lattice's heights from below the bed's deepest layer at the
        # wall's foot to the top
        heights = np.arange(self.latticeFloor - (layers + 1) * s + 0.5 * s, self.wallTop, s)

        def wall(lineX: np.ndarray, lineY: np.ndarray) -> np.ndarray:
            bottom = field.elevation(np.clip(lineX, startX, endX), np.clip(lineY, startY, endY)) - layers * s
            x, y = np.repeat(lineX, heights.size), np.repeat(lineY, heights.size)
            z = np.tile(heights, lineX.size)
            keep = z > np.repeat(bottom, heights.size)
            return np.column_stack([x[keep], y[keep], z[keep]])

        offsets = (np.arange(layers) + 0.5) * s
        for offset in offsets:
            if self.offshoreWall:
                blocks.append(wall(np.full(ys.size, startX - offset), ys))
            if self.endWall:
                blocks.append(wall(np.full(ys.size, endX + offset), ys))
        alongAll = np.concatenate([startX - offsets[::-1], xs, endX + offsets])
        for offset in offsets:
            blocks.append(wall(alongAll, np.full(alongAll.size, startY - offset)))
            blocks.append(wall(alongAll, np.full(alongAll.size, endY + offset)))

        return np.vstack(blocks)

    def enforce(self, particles: ParticleSystem) -> None:

        '''

        Return fluid that has crossed the bed or a wall to the water side, a quarter spacing clear
        of it, and remove its velocity into the solid. Below the bed a particle rises vertically,
        and loses its velocity into the bed along the bed's normal there.

        '''

        fluid = np.nonzero(particles.isFluid)[0]
        positions, velocities = particles.positions, particles.velocities
        clearance = 0.25 * self.spacing
        field = self.field
        startX, endX, startY, endY = field.bounds

        # Bed
        bed = field.elevation(positions[fluid, 0], positions[fluid, 1])
        below = positions[fluid, 2] < bed + clearance
        under = fluid[below]
        if under.size:
            positions[under, 2] = bed[below] + clearance
            normal = field.normal(positions[under, 0], positions[under, 1])
            inward = np.sum(velocities[under] * normal, axis = 1)
            into = inward < 0.0
            velocities[under[into]] -= inward[into, None] * normal[into]

        # Side walls
        low = fluid[positions[fluid, 1] < startY + clearance]
        positions[low, 1] = startY + clearance
        velocities[low, 1] = np.maximum(velocities[low, 1], 0.0)
        high = fluid[positions[fluid, 1] > endY - clearance]
        positions[high, 1] = endY - clearance
        velocities[high, 1] = np.minimum(velocities[high, 1], 0.0)

        # Offshore and shoreward walls
        if self.offshoreWall:
            behind = fluid[positions[fluid, 0] < startX + clearance]
            positions[behind, 0] = startX + clearance
            velocities[behind, 0] = np.maximum(velocities[behind, 0], 0.0)
        limit = endX - clearance if self.endWall else endX
        beyond = fluid[positions[fluid, 0] > limit]
        positions[beyond, 0] = limit
        velocities[beyond, 0] = np.minimum(velocities[beyond, 0], 0.0)

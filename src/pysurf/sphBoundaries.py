
# -- pySurf: SPH Boundaries -- #

'''

Solid walls for SPH: layers of fixed boundary particles, and a guard that keeps fluid on the
right side of them.

Boundary particles follow the dynamic boundary condition of Crespo et al. (2007): they take part
in the density sum and carry a pressure from the equation of state, but they do not move. Fluid
approaching a wall compresses the boundary particles' kernel neighborhoods, their pressure rises,
and the pressure term pushes the fluid back. Several layers keep a fluid particle's kernel support
full at the wall.

    ContainerBoundary   an axis-aligned box with an open top: a sloshing tank
    BedBoundary         a bed of any profile from `pysurf.bathymetry`, with optional vertical walls
                        at either end: a beach, or a channel; the offshore wall can be driven as a
                        piston

Each produces its particle positions and an `enforce` step the solver calls after every
integration. Enforcement is the fallback, not the boundary condition: it catches the rare particle
that a strong impact drives through the particle layers, such as a plunging jet landing on the
beach, by moving it back into the water and removing its velocity into the wall.

References:
-----------
Crespo, A.J.C., Gomez-Gesteira, M. & Dalrymple, R.A. (2007) -- Boundary conditions generated by
    dynamic particles in SPH methods, CMC: Computers, Materials & Continua 5(3), 173-184.
Monaghan & Kos (1999) -- Solitary waves on a Cretan beach, J. Waterway, Port, Coastal, Ocean
    Eng. 125(3), 145-154.

----------------------------------------------------------------------
                            Validation status
----------------------------------------------------------------------

Geometry and bookkeeping only; the physics of the wall is the solver's. tests/testSphBoundaries.py
checks that boundary layers sit at the intended offsets from the wall, keep the lattice spacing
along it, and that enforcement returns a penetrating particle to the water with no velocity into
the wall. The wall's effect on a flow is validated through the sloshing tank in
tests/testValidationSloshing.py.

Sean Bowman [10/11/2026]

'''

# Standard library imports
from __future__ import annotations

# Third-party imports
import numpy as np

# Local imports
from pysurf.bathymetry import Bathymetry
from pysurf.sphParticles import ParticleSystem

class ContainerBoundary:

    '''

    An axis-aligned container: floor and side walls, open at the top unless asked otherwise.

    Parameters:
    -----------
    containerMin : np.ndarray
        Lower corner of the container interior [m]
    containerMax : np.ndarray
        Upper corner of the container interior [m]
    spacing : float
        Lattice spacing, matching the fluid's [m]
    nLayers : int
        Boundary particle layers behind each face
    openTop : bool
        No boundary particles on the top face

    '''

    def __init__(self, containerMin: np.ndarray, containerMax: np.ndarray, spacing: float,
                 nLayers: int = 3, openTop: bool = True) -> None:

        self.containerMin = np.asarray(containerMin, dtype = float).copy()
        self.containerMax = np.asarray(containerMax, dtype = float).copy()
        self.spacing = spacing      # [m]
        self.nLayers = nLayers
        self.openTop = openTop

    @property
    def dimensions(self) -> int:
        '''Number of spatial dimensions.'''
        return len(self.containerMin)

    def positions(self) -> np.ndarray:

        '''

        Boundary particle positions: the shell nLayers deep around the container interior, less
        the top face when open. Each face's layers are anchored to that face, half a spacing
        apart, so the gap to the fluid is one spacing on every face whatever the container size.

        '''

        s, layers = self.spacing, self.nLayers
        offsets = (np.arange(layers) + 0.5) * s

        axes = []
        for axis, (low, high) in enumerate(zip(self.containerMin, self.containerMax)):
            pieces = [low - offsets[::-1], np.arange(low + s / 2.0, high, s)]
            if not (self.openTop and axis == self.dimensions - 1):
                pieces.append(high + offsets)
            axes.append(np.concatenate(pieces))
        grids = np.meshgrid(*axes, indexing = 'xy')
        points = np.column_stack([grid.ravel() for grid in grids])

        interior = np.all((points > self.containerMin) & (points < self.containerMax), axis = 1)
        if self.openTop:
            # Above the floor and between the side walls is interior all the way up
            between = np.all((points[:, :-1] > self.containerMin[:-1]) & (points[:, :-1] < self.containerMax[:-1]), axis = 1)
            interior = between & (points[:, -1] > self.containerMin[-1])

        return points[~interior]

    def enforce(self, particles: ParticleSystem) -> None:

        '''

        Return any fluid particle outside the container to its face and remove its velocity
        through that face.

        '''

        fluid = particles.isFluid
        positions, velocities = particles.positions, particles.velocities

        for axis in range(self.dimensions):
            below = fluid & (positions[:, axis] < self.containerMin[axis])
            positions[below, axis] = self.containerMin[axis]
            velocities[below, axis] = np.maximum(velocities[below, axis], 0.0)

            if axis == self.dimensions - 1 and self.openTop:
                continue
            above = fluid & (positions[:, axis] > self.containerMax[axis])
            positions[above, axis] = self.containerMax[axis]
            velocities[above, axis] = np.minimum(velocities[above, axis], 0.0)

class BedBoundary:

    '''

    A bed of any profile, with optional vertical walls at its offshore and shoreward ends; 2D, or
    extruded across a channel of the given width in 3D.

    Bed particles sit in layers below the bed, offset along its normal by (layer + 1/2) spacing,
    and spaced one lattice spacing apart along it. The offshore wall's layers sit behind x = startX
    and run from below the bed to `wallTop`; the shoreward wall's sit beyond x = endX up to
    `endWallTop`. In 3D the bed and offshore wall are repeated across the channel, and front and
    back walls close its sides. The vertical axis is the last coordinate.

    The offshore wall can be driven as a piston: `attachPiston` takes its particles, and
    `movePiston` moves them and gives them the piston's velocity. Over a flat or rising bed the
    wall's columns, which reach below the bed, keep the corner closed as it advances.

    Parameters:
    -----------
    bathymetry : Bathymetry
        The bed profile
    spacing : float
        Lattice spacing, matching the fluid's [m]
    nLayers : int
        Boundary particle layers
    wallTop : float | None
        Top of the offshore wall, and of the side walls in 3D [m]; None for no offshore wall
    width : float | None
        Channel width for a 3D boundary [m]; None for 2D
    endWallTop : float | None
        Top of the shoreward wall [m], 2D only; None for no shoreward wall

    '''

    def __init__(self, bathymetry: Bathymetry, spacing: float, nLayers: int = 3,
                 wallTop: float | None = None, width: float | None = None, endWallTop: float | None = None) -> None:

        self.bathymetry = bathymetry
        self.spacing = spacing      # [m]
        self.nLayers = nLayers
        self.wallTop = wallTop      # [m]
        self.width = width          # [m]
        self.endWallTop = endWallTop                # [m]
        self.wallX = bathymetry.startX              # [m], the offshore wall, which a piston moves
        self._pistonMask: np.ndarray | None = None

    def _profilePositions(self) -> np.ndarray:

        '''The 2D bed and offshore wall layers, in (x, z).'''

        s = self.spacing
        bedX, bedZ = self.bathymetry.sample(s)
        bedNormal = self.bathymetry.normal(bedX)

        layers = []
        for layer in range(self.nLayers):
            offset = (layer + 0.5) * s
            layers.append(np.column_stack([bedX, bedZ]) - offset * bedNormal)

        # The wall columns reach down past the deepest bed layer, so the corners are closed
        for wallX, top, side in ((self.bathymetry.startX, self.wallTop, -1.0),
                                 (self.bathymetry.endX, self.endWallTop, 1.0)):
            if top is None:
                continue
            bottom = float(self.bathymetry.elevation(wallX)) - self.nLayers * s
            heights = np.arange(bottom + s / 2.0, top, s)
            for layer in range(self.nLayers):
                layers.append(np.column_stack([np.full_like(heights, wallX + side * (layer + 0.5) * s), heights]))

        return np.vstack(layers)

    def positions(self) -> np.ndarray:

        '''Boundary particle positions, shape (N, 2), or (N, 3) with a channel width.'''

        profile = self._profilePositions()
        if self.width is None:
            return profile

        s, layers = self.spacing, self.nLayers
        offsets = (np.arange(layers) + 0.5) * s

        # Bed and offshore wall repeated across the channel and under the side walls
        across = np.concatenate([-offsets[::-1], np.arange(s / 2.0, self.width, s), self.width + offsets])
        extruded = np.column_stack([np.repeat(profile[:, 0], across.size), np.tile(across, len(profile)),
                                    np.repeat(profile[:, 1], across.size)])

        # Side walls: every lattice height from below the bed to the wall top, at each bed station
        top = self.wallTop if self.wallTop is not None else float(np.max(self.bathymetry.z)) + layers * s
        bedX, _ = self.bathymetry.sample(s)
        heights = np.arange(float(np.min(self.bathymetry.z)) - layers * s + s / 2.0, top, s)
        xGrid, zGrid = np.meshgrid(bedX, heights, indexing = 'xy')
        keep = zGrid > self.bathymetry.elevation(xGrid) - layers * s
        xWall, zWall = xGrid[keep], zGrid[keep]
        sides = [np.column_stack([xWall, np.full_like(xWall, y), zWall])
                 for y in np.concatenate([-offsets, self.width + offsets])]

        return np.vstack([extruded] + sides)

    def attachPiston(self, particles: ParticleSystem) -> None:

        '''

        Take the offshore wall's particles, the boundary particles behind x = startX, as a piston.

        Raises:
        -------
        ValueError : If the boundary has no offshore wall.

        '''

        if self.wallTop is None:
            raise ValueError('A piston needs the offshore wall; give the boundary a wallTop.')
        self._pistonMask = (~particles.isFluid) & (particles.positions[:, 0] < self.bathymetry.startX - 0.25 * self.spacing)

    def movePiston(self, particles: ParticleSystem, x: float, velocity: float) -> None:

        '''

        Move the offshore wall to x [m], moving along the channel at `velocity` [m/s].

        Raises:
        -------
        RuntimeError : If `attachPiston` was not called first.

        '''

        if self._pistonMask is None:
            raise RuntimeError('No piston attached. Call attachPiston first.')
        particles.positions[self._pistonMask, 0] += x - self.wallX
        particles.velocities[self._pistonMask] = 0.0
        particles.velocities[self._pistonMask, 0] = velocity
        self.wallX = x

    def enforce(self, particles: ParticleSystem) -> None:

        '''

        Return fluid that has crossed the bed or a wall to the water side, a quarter spacing
        clear of the surface, and remove its velocity into the solid; past a piston, the velocity
        relative to it.

        '''

        fluid = np.nonzero(particles.isFluid)[0]
        positions, velocities = particles.positions, particles.velocities
        clearance = 0.25 * self.spacing

        # Bed: compare each particle with the bed elevation beneath it, in the (x, vertical) plane
        bedZ = self.bathymetry.elevation(positions[fluid, 0])
        under = fluid[positions[fluid, -1] < bedZ + clearance]
        if under.size:
            positions[under, -1] = self.bathymetry.elevation(positions[under, 0]) + clearance
            normal = self.bathymetry.normal(positions[under, 0])
            planeVelocity = velocities[under][:, [0, -1]]
            inward = np.sum(planeVelocity * normal, axis = 1)
            into = inward < 0.0
            correction = inward[into, None] * normal[into]
            velocities[under[into], 0] -= correction[:, 0]
            velocities[under[into], -1] -= correction[:, 1]

        # Side walls of a 3D channel
        if self.width is not None:
            for bound, side in ((clearance, 'low'), (self.width - clearance, 'high')):
                if side == 'low':
                    outside = fluid[positions[fluid, 1] < bound]
                    velocities[outside, 1] = np.maximum(velocities[outside, 1], 0.0)
                else:
                    outside = fluid[positions[fluid, 1] > bound]
                    velocities[outside, 1] = np.minimum(velocities[outside, 1], 0.0)
                positions[outside, 1] = bound

        # Offshore wall, which may be a moving piston, and the shoreward end of the profile
        endX = self.bathymetry.endX
        if self.wallTop is not None:
            pistonSpeed = float(particles.velocities[self._pistonMask, 0][0]) if (
                self._pistonMask is not None and self._pistonMask.any()) else 0.0
            behind = fluid[positions[fluid, 0] < self.wallX + clearance]
            positions[behind, 0] = self.wallX + clearance
            velocities[behind, 0] = np.maximum(velocities[behind, 0], pistonSpeed)
        limit = endX - clearance if self.endWallTop is not None else endX
        beyond = fluid[positions[fluid, 0] > limit]
        positions[beyond, 0] = limit
        velocities[beyond, 0] = np.minimum(velocities[beyond, 0], 0.0)
